#!/usr/bin/env python3
"""Generate art.js (shared pixel art palette, tile painters and 8-bit sfx) from game.js so the
big-map mode (world.html) reuses exactly the same art/sounds as the 30-level mode.
Re-run after editing art in game.js:  python3 tools/extract-art.py"""
import re,os
here=os.path.dirname(os.path.abspath(__file__));src=open(os.path.join(here,'..','game.js')).read().split('\n')
def span(a,b):
    i=next(k for k,l in enumerate(src) if l.startswith(a));j=next(k for k,l in enumerate(src) if k>i and l.startswith(b));return src[i:j]
out=['// GENERATED by tools/extract-art.py from game.js — do not edit by hand.',
 '// Globals expected from the host script: o (offscreen 2d ctx), T (time), L (level view), st (state view), TH (theme), save ({mute}).']
out+=span('const E32=','let TH=WORLDS.grass;')
out+=['const KC=base.keys;','const TS=16;','const R=(x,y,w,h,c)=>{o.fillStyle=c;o.fillRect(Math.round(x),Math.round(y),w,h)};']
out+=[l for l in src if l.startswith('const hash=')]
out+=span('// ===== SOUND','// ===== DAILY') if any(l.startswith('// ===== DAILY') for l in src) else span('// ===== SOUND','let curMin')
out+=span('// ===== RENDER','let lastDraw=0;')
open(os.path.join(here,'..','art.js'),'w').write('\n'.join(out)+'\n')
print('art.js',len(out),'lines')
